// Shared schema and helpers of the S-04 vector files (monoptah-ik.ts.json, monoptah-ik.snow.json).
// The Rust side (rust/src/lib.rs) reads and writes the same JSON.
import { bytesToHex, hexToBytes } from "@noble/hashes/utils.js";

export const PROTOCOL = "Noise_IK_25519_ChaChaPoly_SHA256";

/** A byte string in JSON: `{"hex": "..."}` or `{"fill": "<one byte hex>", "length": N}` (same forms as protocol/vectors.json). */
export type ByteStr = { hex: string } | { fill: string; length: number };

export function bs(bytes: Uint8Array): ByteStr {
  // Store long runs of one byte compactly.
  const first = bytes[0];
  if (bytes.length >= 64 && first !== undefined && bytes.every((b) => b === first)) {
    return { fill: bytesToHex(Uint8Array.of(first)), length: bytes.length };
  }
  return { hex: bytesToHex(bytes) };
}

export function unbs(value: ByteStr): Uint8Array {
  if ("hex" in value) return hexToBytes(value.hex);
  return new Uint8Array(value.length).fill(hexToBytes(value.fill)[0] as number);
}

export interface Party {
  /** X25519 private key (obviously fake). */
  static: ByteStr;
  /** Fixed ephemeral private key. */
  ephemeral: ByteStr;
}

export type TransportStep =
  | { from: "initiator" | "responder"; plaintext: ByteStr; ciphertext: ByteStr }
  /** Rekey the cipher of one direction: the sender's send state and the receiver's recv state. */
  | { rekey: "initiator->responder" | "responder->initiator" };

export interface PositiveCase {
  name: string;
  prologue: ByteStr;
  initiator: Party;
  responder: Party;
  /** The two handshake messages with their payloads. */
  handshake: [{ payload: ByteStr; message: ByteStr }, { payload: ByteStr; message: ByteStr }];
  /** Public keys, for cross-checking the DH implementation. */
  publicKeys: { initiatorStatic: ByteStr; responderStatic: ByteStr };
  /** Handshake hash (H after split) as each side reports it; equal. */
  handshakeHash: { initiator: ByteStr; responder: ByteStr };
  transport: TransportStep[];
}

export interface NegativeCase {
  name: string;
  /** What the case checks. */
  kind: "wrong_prologue" | "wrong_responder_static";
  initiatorPrologue: ByteStr;
  responderPrologue: ByteStr;
  initiator: Party;
  /** The responder static PUBLIC key the initiator believes in. */
  initiatorRemoteStatic: ByteStr;
  /** The real responder static private key. */
  responderStatic: ByteStr;
  /** Message 1 as the initiator produces it. The responder must fail to read it. */
  message1: ByteStr;
}

export interface VectorFile {
  $comment: string;
  version: 1;
  generator: "ts" | "snow";
  protocol: typeof PROTOCOL;
  cases: PositiveCase[];
  negative: NegativeCase[];
}

