//! Spike S-04: Noise_IK_25519_ChaChaPoly_SHA256 with `snow`, replaying the vector files shared with the
//! TypeScript implementation (web/app/src/link/noise.ts).
use curve25519_dalek::montgomery::MontgomeryPoint;
use serde::{Deserialize, Serialize};
use snow::{Builder, HandshakeState, TransportState};

pub const PROTOCOL: &str = "Noise_IK_25519_ChaChaPoly_SHA256";
pub const MAX_NOISE_MESSAGE: usize = 65_535;
pub const TAG_LEN: usize = 16;
pub const MAX_TRANSPORT_PLAINTEXT: usize = MAX_NOISE_MESSAGE - TAG_LEN;

pub const COMMENT: &str = "Generated by gen-ts-vectors.ts (ts) or `cargo run --bin gen` (snow) in web/spikes/s-04-noise. Never edit by hand. \
All keys are obviously fake (bytes repeating one value). Byte strings are {hex} or {fill, length}. \
cases[]: a full IK handshake (2 messages with payloads) then transport steps. transport[]: {from, plaintext, ciphertext} where the sender encrypts \
with its send CipherState (nonce counts per direction) and the receiver must decrypt to the plaintext; or {rekey: direction} which rekeys that \
direction's CipherState on both sides. negative[]: message1 must be rejected by the responder (it fails reading message 1).";

// ---------------------------------------------------------------- byte strings

#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
#[serde(untagged)]
pub enum ByteStr {
    Hex { hex: String },
    Fill { fill: String, length: usize },
}

pub fn to_hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

pub fn from_hex(text: &str) -> Result<Vec<u8>, String> {
    if !text.len().is_multiple_of(2) {
        return Err(format!("odd hex length {}", text.len()));
    }
    (0..text.len() / 2)
        .map(|i| {
            u8::from_str_radix(&text[2 * i..2 * i + 2], 16).map_err(|e| format!("bad hex: {e}"))
        })
        .collect()
}

impl ByteStr {
    pub fn from_bytes(bytes: &[u8]) -> Self {
        match bytes.first() {
            Some(&first) if bytes.len() >= 64 && bytes.iter().all(|&b| b == first) => {
                ByteStr::Fill {
                    fill: to_hex(&[first]),
                    length: bytes.len(),
                }
            }
            _ => ByteStr::Hex { hex: to_hex(bytes) },
        }
    }

    pub fn bytes(&self) -> Result<Vec<u8>, String> {
        match self {
            ByteStr::Hex { hex } => from_hex(hex),
            ByteStr::Fill { fill, length } => {
                let one = from_hex(fill)?;
                if one.len() != 1 {
                    return Err("fill must be one byte".into());
                }
                Ok(vec![one[0]; *length])
            }
        }
    }
}

