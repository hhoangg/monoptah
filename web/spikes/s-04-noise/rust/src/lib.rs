// ---------------------------------------------------------------- helpers

#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Role {
    Initiator,
    Responder,
}

pub fn public_key(private: &[u8]) -> Vec<u8> {
    let key: [u8; 32] = private.try_into().expect("32-byte private key");
    MontgomeryPoint::mul_base_clamped(key).to_bytes().to_vec()
}

fn build(
    role: Role,
    prologue: &[u8],
    static_private: &[u8],
    ephemeral_private: &[u8],
    remote_static_public: Option<&[u8]>,
) -> Result<HandshakeState, String> {
    let params = PROTOCOL.parse().map_err(|e| format!("params: {e:?}"))?;
    let mut builder = Builder::new(params)
        .prologue(prologue)
        .map_err(|e| e.to_string())?
        .local_private_key(static_private)
        .map_err(|e| e.to_string())?
        .fixed_ephemeral_key_for_testing_only(ephemeral_private);
    if let Some(rs) = remote_static_public {
        builder = builder.remote_public_key(rs).map_err(|e| e.to_string())?;
    }
    match role {
        Role::Initiator => builder.build_initiator(),
        Role::Responder => builder.build_responder(),
    }
    .map_err(|e| e.to_string())
}

fn write(hs: &mut HandshakeState, payload: &[u8]) -> Result<Vec<u8>, String> {
    let mut buf = vec![0u8; MAX_NOISE_MESSAGE];
    let n = hs
        .write_message(payload, &mut buf)
        .map_err(|e| e.to_string())?;
    buf.truncate(n);
    Ok(buf)
}

fn read(hs: &mut HandshakeState, message: &[u8]) -> Result<Vec<u8>, String> {
    let mut buf = vec![0u8; MAX_NOISE_MESSAGE];
    let n = hs
        .read_message(message, &mut buf)
        .map_err(|e| e.to_string())?;
    buf.truncate(n);
    Ok(buf)
}

fn t_write(ts: &mut TransportState, payload: &[u8]) -> Result<Vec<u8>, String> {
    let mut buf = vec![0u8; MAX_NOISE_MESSAGE];
    let n = ts
        .write_message(payload, &mut buf)
        .map_err(|e| e.to_string())?;
    buf.truncate(n);
    Ok(buf)
}

fn t_read(ts: &mut TransportState, message: &[u8]) -> Result<Vec<u8>, String> {
    let mut buf = vec![0u8; MAX_NOISE_MESSAGE];
    let n = ts
        .read_message(message, &mut buf)
        .map_err(|e| e.to_string())?;
    buf.truncate(n);
    Ok(buf)
}

fn eq(what: &str, got: &[u8], want: &[u8]) -> Result<(), String> {
    if got == want {
        Ok(())
    } else {
        Err(format!(
            "{what}: bytes differ (got {} bytes, want {} bytes)",
            got.len(),
            want.len()
        ))
    }
}

// ---------------------------------------------------------------- generic script (both formats map onto it)

pub struct Script {
    pub prologue: Vec<u8>,
    pub init_static: Vec<u8>,
    pub init_ephemeral: Vec<u8>,
    pub resp_static: Vec<u8>,
    pub resp_ephemeral: Vec<u8>,
    /// (payload, message) for messages 1 and 2.
    pub handshake: [(Vec<u8>, Vec<u8>); 2],
    pub hash: Option<Vec<u8>>,
    pub transport: Vec<ScriptStep>,
}

pub enum ScriptStep {
    /// `from_initiator`, plaintext, ciphertext.
    Message(bool, Vec<u8>, Vec<u8>),
    /// true: initiator -> responder direction.
    Rekey(bool),
}

pub fn script_of_case(case: &PositiveCase) -> Result<Script, String> {
    if case.handshake.len() != 2 {
        return Err("a case needs exactly 2 handshake messages".into());
    }
    let hs = |i: usize| -> Result<(Vec<u8>, Vec<u8>), String> {
        Ok((
            case.handshake[i].payload.bytes()?,
            case.handshake[i].message.bytes()?,
        ))
    };
    let mut transport = Vec::new();
    for step in &case.transport {
        transport.push(match step {
            TransportStep::Message {
                from,
                plaintext,
                ciphertext,
            } => ScriptStep::Message(from == "initiator", plaintext.bytes()?, ciphertext.bytes()?),
            TransportStep::Rekey { rekey } => ScriptStep::Rekey(rekey == "initiator->responder"),
        });
    }
    let a = case.handshake_hash.initiator.bytes()?;
    let b = case.handshake_hash.responder.bytes()?;
    eq("recorded initiator hash vs responder hash", &a, &b)?;
    Ok(Script {
        prologue: case.prologue.bytes()?,
        init_static: case.initiator.static_key.bytes()?,
        init_ephemeral: case.initiator.ephemeral.bytes()?,
        resp_static: case.responder.static_key.bytes()?,
        resp_ephemeral: case.responder.ephemeral.bytes()?,
        handshake: [hs(0)?, hs(1)?],
        hash: Some(a),
        transport,
    })
}

/// Published vectors: messages 0 and 1 are the handshake, then transport alternating initiator, responder.
pub fn script_of_published(v: &PublishedVector) -> Result<Script, String> {
    if v.init_prologue != v.resp_prologue {
        return Err("prologues differ".into());
    }
    if v.messages.len() < 2 {
        return Err("too few messages".into());
    }
    let msg = |i: usize| -> Result<(Vec<u8>, Vec<u8>), String> {
        Ok((
            from_hex(&v.messages[i].payload)?,
            from_hex(&v.messages[i].ciphertext)?,
        ))
    };
    let mut transport = Vec::new();
    for i in 2..v.messages.len() {
        let (p, c) = msg(i)?;
        transport.push(ScriptStep::Message(i % 2 == 0, p, c));
    }
    let script = Script {
        prologue: from_hex(&v.init_prologue)?,
        init_static: from_hex(&v.init_static)?,
        init_ephemeral: from_hex(&v.init_ephemeral)?,
        resp_static: from_hex(&v.resp_static)?,
        resp_ephemeral: from_hex(&v.resp_ephemeral)?,
        handshake: [msg(0)?, msg(1)?],
        hash: v.handshake_hash.as_deref().map(from_hex).transpose()?,
        transport,
    };
    eq(
        "init_remote_static is the responder public key",
        &from_hex(&v.init_remote_static)?,
        &public_key(&script.resp_static),
    )?;
    Ok(script)
}

/// Replays `script` with snow playing `role`, the peer being the recorded bytes. Byte equality of every
/// message this side produces, plaintext equality of every message it consumes, handshake hash if recorded.
pub fn replay(script: &Script, role: Role) -> Result<(), String> {
    let me_init = role == Role::Initiator;
    let (own_static, own_eph, remote) = if me_init {
        (
            &script.init_static,
            &script.init_ephemeral,
            Some(public_key(&script.resp_static)),
        )
    } else {
        (&script.resp_static, &script.resp_ephemeral, None)
    };
    let mut hs = build(
        role,
        &script.prologue,
        own_static,
        own_eph,
        remote.as_deref(),
    )?;
    for (i, (payload, message)) in script.handshake.iter().enumerate() {
        let my_turn = me_init == (i == 0);
        if my_turn {
            eq(
                &format!("handshake message {}", i + 1),
                &write(&mut hs, payload)?,
                message,
            )?;
        } else {
            eq(
                &format!("handshake payload {}", i + 1),
                &read(&mut hs, message)?,
                payload,
            )?;
        }
    }
    if !hs.is_handshake_finished() {
        return Err("handshake not finished".into());
    }
    if let Some(want) = &script.hash {
        eq("handshake hash", hs.get_handshake_hash(), want)?;
    }
    if !me_init {
        // The responder learns the initiator static key from message 1.
        eq(
            "remote static",
            hs.get_remote_static().ok_or("no remote static")?,
            &public_key(&script.init_static),
        )?;
    }
    let mut ts = hs.into_transport_mode().map_err(|e| e.to_string())?;
    for (i, step) in script.transport.iter().enumerate() {
        match step {
            ScriptStep::Rekey(i_to_r) => {
                if *i_to_r == me_init {
                    ts.rekey_outgoing();
                } else {
                    ts.rekey_incoming();
                }
            }
            ScriptStep::Message(from_initiator, plaintext, ciphertext) => {
                if *from_initiator == me_init {
                    eq(
                        &format!("transport step {i} ciphertext"),
                        &t_write(&mut ts, plaintext)?,
                        ciphertext,
                    )?;
                } else {
                    eq(
                        &format!("transport step {i} plaintext"),
                        &t_read(&mut ts, ciphertext)?,
                        plaintext,
                    )?;
                }
            }
        }
    }
    Ok(())
}

/// A negative case must make the responder fail reading message 1.
pub fn replay_negative(case: &NegativeCase) -> Result<(), String> {
    let init_eph = case.initiator.ephemeral.bytes()?;
    // Self-check: the initiator side built here reproduces message 1 (so the vector is what it claims).
    let mut init = build(
        Role::Initiator,
        &case.initiator_prologue.bytes()?,
        &case.initiator.static_key.bytes()?,
        &init_eph,
        Some(&case.initiator_remote_static.bytes()?),
    )?;
    let m1 = write(&mut init, b"negative case payload")?;
    eq(
        "negative message 1 reproduced",
        &m1,
        &case.message1.bytes()?,
    )?;
    let mut resp = build(
        Role::Responder,
        &case.responder_prologue.bytes()?,
        &case.responder_static.bytes()?,
        &[7u8; 32],
        None,
    )?;
    match read(&mut resp, &case.message1.bytes()?) {
        Ok(_) => Err(format!(
            "negative case {}: responder accepted message 1",
            case.name
        )),
        Err(_) => Ok(()),
    }
}

// ---------------------------------------------------------------- generator (snow side)

const KEY_INIT_STATIC: [u8; 32] = [0x11; 32];
const KEY_INIT_EPH: [u8; 32] = [0x12; 32];
const KEY_RESP_STATIC: [u8; 32] = [0x13; 32];
const KEY_RESP_EPH: [u8; 32] = [0x14; 32];
const KEY_WRONG_RESP_STATIC: [u8; 32] = [0x15; 32];

pub enum PlanStep {
    Send(bool, Vec<u8>),
    Rekey(bool),
}

/// Deterministic non-uniform bytes (same formula as the TS generator, different seeds are used).
pub fn pattern(length: usize, seed: usize) -> Vec<u8> {
    (0..length)
        .map(|i| ((seed + i * 31) & 0xff) as u8)
        .collect()
}

fn party(role: Role) -> Party {
    match role {
        Role::Initiator => Party {
            static_key: ByteStr::from_bytes(&KEY_INIT_STATIC),
            ephemeral: ByteStr::from_bytes(&KEY_INIT_EPH),
        },
        Role::Responder => Party {
            static_key: ByteStr::from_bytes(&KEY_RESP_STATIC),
            ephemeral: ByteStr::from_bytes(&KEY_RESP_EPH),
        },
    }
}

fn positive(
    name: &str,
    prologue: &[u8],
    p1: &[u8],
    p2: &[u8],
    plan: &[PlanStep],
) -> Result<PositiveCase, String> {
    let resp_pub = public_key(&KEY_RESP_STATIC);
    let mut init = build(
        Role::Initiator,
        prologue,
        &KEY_INIT_STATIC,
        &KEY_INIT_EPH,
        Some(&resp_pub),
    )?;
    let mut resp = build(
        Role::Responder,
        prologue,
        &KEY_RESP_STATIC,
        &KEY_RESP_EPH,
        None,
    )?;
    let m1 = write(&mut init, p1)?;
    eq("payload 1", &read(&mut resp, &m1)?, p1)?;
    let m2 = write(&mut resp, p2)?;
    eq("payload 2", &read(&mut init, &m2)?, p2)?;
    let ih = init.get_handshake_hash().to_vec();
    let rh = resp.get_handshake_hash().to_vec();
    eq("hash", &ih, &rh)?;
    let mut ic = init.into_transport_mode().map_err(|e| e.to_string())?;
    let mut rc = resp.into_transport_mode().map_err(|e| e.to_string())?;
    let mut transport = Vec::new();
    for step in plan {
        match step {
            PlanStep::Rekey(i_to_r) => {
                if *i_to_r {
                    ic.rekey_outgoing();
                    rc.rekey_incoming();
                } else {
                    rc.rekey_outgoing();
                    ic.rekey_incoming();
                }
                transport.push(TransportStep::Rekey {
                    rekey: if *i_to_r {
                        "initiator->responder"
                    } else {
                        "responder->initiator"
                    }
                    .into(),
                });
            }
            PlanStep::Send(from_initiator, plaintext) => {
                let (s, r) = if *from_initiator {
                    (&mut ic, &mut rc)
                } else {
                    (&mut rc, &mut ic)
                };
                let ct = t_write(s, plaintext)?;
                eq("self roundtrip", &t_read(r, &ct)?, plaintext)?;
                transport.push(TransportStep::Message {
                    from: if *from_initiator {
                        "initiator"
                    } else {
                        "responder"
                    }
                    .into(),
                    plaintext: ByteStr::from_bytes(plaintext),
                    ciphertext: ByteStr::Hex { hex: to_hex(&ct) },
                });
            }
        }
    }
    Ok(PositiveCase {
        name: name.into(),
        prologue: ByteStr::from_bytes(prologue),
        initiator: party(Role::Initiator),
        responder: party(Role::Responder),
        handshake: vec![
            HandshakeMessage {
                payload: ByteStr::from_bytes(p1),
                message: ByteStr::Hex { hex: to_hex(&m1) },
            },
            HandshakeMessage {
                payload: ByteStr::from_bytes(p2),
                message: ByteStr::Hex { hex: to_hex(&m2) },
            },
        ],
        public_keys: PublicKeys {
            initiator_static: ByteStr::from_bytes(&public_key(&KEY_INIT_STATIC)),
            responder_static: ByteStr::from_bytes(&resp_pub),
        },
        handshake_hash: HandshakeHash {
            initiator: ByteStr::from_bytes(&ih),
            responder: ByteStr::from_bytes(&rh),
        },
        transport,
    })
}

fn negative(
    name: &str,
    kind: &str,
    init_prologue: &[u8],
    resp_prologue: &[u8],
    believed_resp_private: &[u8; 32],
) -> Result<NegativeCase, String> {
    let believed_pub = public_key(believed_resp_private);
    let mut init = build(
        Role::Initiator,
        init_prologue,
        &KEY_INIT_STATIC,
        &KEY_INIT_EPH,
        Some(&believed_pub),
    )?;
    let m1 = write(&mut init, b"negative case payload")?;
    Ok(NegativeCase {
        name: name.into(),
        kind: kind.into(),
        initiator_prologue: ByteStr::from_bytes(init_prologue),
        responder_prologue: ByteStr::from_bytes(resp_prologue),
        initiator: party(Role::Initiator),
        initiator_remote_static: ByteStr::from_bytes(&believed_pub),
        responder_static: ByteStr::from_bytes(&KEY_RESP_STATIC),
        message1: ByteStr::Hex { hex: to_hex(&m1) },
    })
}

/// `"monoptah-web/1" || desktopId(16) || deviceId(16) || channel(u16 BE)`, with obviously fake ids.
pub fn monoptah_prologue(desktop_last: u8, device_last: u8, channel: u16) -> Vec<u8> {
    let mut out = b"monoptah-web/1".to_vec();
    for last in [desktop_last, device_last] {
        let mut id = [0xee_u8; 16];
        id[15] = last;
        out.extend_from_slice(&id);
    }
    out.extend_from_slice(&channel.to_be_bytes());
    out
}

pub fn build_vectors() -> Result<VectorFile, String> {
    use PlanStep::{Rekey, Send};
    let pro = monoptah_prologue(0x21, 0x22, 9);
    let wrong = monoptah_prologue(0x21, 0x22, 10);
    let cases = vec![
        positive(
            "plain-empty-prologue-empty-payloads",
            &[],
            &[],
            &[],
            &[
                Send(true, b"snow hello".to_vec()),
                Send(false, b"snow world".to_vec()),
            ],
        )?,
        positive(
            "monoptah-prologue-with-payloads",
            &pro,
            b"snow payload one",
            &pattern(40, 5),
            &[
                Send(true, b"initiator first".to_vec()),
                Send(false, pattern(150, 11)),
                Send(true, vec![]),
                Send(true, pattern(2000, 13)),
                Send(false, vec![]),
                Send(false, b"responder last".to_vec()),
            ],
        )?,
        positive(
            "max-size-transport",
            &pro,
            &[],
            &[],
            &[
                Send(true, vec![0x3c; MAX_TRANSPORT_PLAINTEXT]),
                Send(false, vec![0xc3; MAX_TRANSPORT_PLAINTEXT]),
                Send(false, b"small after max".to_vec()),
            ],
        )?,
        positive(
            "rekey-each-direction",
            &pro,
            b"s1",
            b"s2",
            &[
                Send(true, b"pre i".to_vec()),
                Send(false, b"pre r".to_vec()),
                Rekey(true),
                Send(true, b"post rekey i".to_vec()),
                Send(false, b"r still on first key".to_vec()),
                Rekey(false),
                Send(false, b"post rekey r".to_vec()),
                Rekey(true),
                Rekey(true),
                Send(true, pattern(400, 99)),
                Send(true, b"one more".to_vec()),
                Send(false, b"and back".to_vec()),
            ],
        )?,
    ];
    Ok(VectorFile {
        comment: COMMENT.into(),
        version: 1,
        generator: "snow".into(),
        protocol: PROTOCOL.into(),
        cases,
        negative: vec![
            negative(
                "wrong-prologue",
                "wrong_prologue",
                &pro,
                &wrong,
                &KEY_RESP_STATIC,
            )?,
            negative(
                "wrong-responder-static",
                "wrong_responder_static",
                &pro,
                &pro,
                &KEY_WRONG_RESP_STATIC,
            )?,
        ],
    })
}
