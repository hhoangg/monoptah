//! User-supplied Claude Code credentials (setup-token or API key). The secret
//! is stored AES-256-GCM encrypted in the native store database; the key lives
//! in a separate file next to it, never in the database itself.
use super::sealed::{
    create_key, decrypt, encrypt, inspect_key, read_key, write_temp_key, KeyError, KeyState,
    KEY_FILE, KEY_LEN, NONCE_LEN,
};
use super::Profile;
use crate::provider::Kind;
use rusqlite::{params, Connection, OpenFlags, OptionalExtension};
use std::path::{Path, PathBuf};

/// Shown when a saved credential cannot be read or decrypted.
pub const CREDENTIAL_UNREADABLE: &str =
    "Could not read the saved Claude credential. Replace the token or API key in Accounts.";
const UNAVAILABLE: &str = CREDENTIAL_UNREADABLE;
const DAMAGED_KEY: &str = "The key file for saved Claude credentials is damaged and other accounts depend on it. Restore credentials.key, or remove their saved tokens, then try again.";
const SAVE_FAILED: &str = "Could not save the Claude credential.";
const CLEAR_FAILED: &str = "Could not clear this account's saved credential.";
const PROVIDER: &str = "claude";
/// Credential kind name, nonce and ciphertext of a saved row.
type StoredRow = (String, Vec<u8>, Vec<u8>);

/// DDL for the credential table, shared with the native store schema.
pub(crate) const CREDENTIALS_TABLE: &str =
    "CREATE TABLE IF NOT EXISTS provider_account_credentials(
  provider TEXT NOT NULL, account_id TEXT NOT NULL, kind TEXT NOT NULL,
  nonce BLOB NOT NULL, ciphertext BLOB NOT NULL, PRIMARY KEY(provider, account_id));";

/// Accept terminal line wrapping, but never commands, quotes or other output.
/// This checks syntax only; Claude Code verifies the credential when it runs.
pub fn normalize_claude_token(value: &str) -> Result<String, String> {
    let token: String = value.chars().filter(|c| !c.is_ascii_whitespace()).collect();
    if token.len() > 8192
        || !token.starts_with("sk-ant-oat01-")
        || token.len() <= "sk-ant-oat01-".len()
        || !token
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'-' | b'_'))
    {
        return Err(
            "Paste only the token generated by claude setup-token (starting with sk-ant-oat01-)."
                .into(),
        );
    }
    Ok(token)
}

/// Claude's `-p` rejects an API key that is not pasted whole, so be strict.
pub fn normalize_claude_api_key(value: &str) -> Result<String, String> {
    let key: String = value.chars().filter(|c| !c.is_ascii_whitespace()).collect();
    if key.len() > 8192
        || !key.starts_with("sk-ant-api")
        || key.len() <= "sk-ant-api".len()
        // A bare version prefix such as `sk-ant-api03-` has no key body.
        || key.rsplit('-').next().is_none_or(str::is_empty)
        || !key
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'-' | b'_'))
    {
        return Err("Paste only an Anthropic API key (starting with sk-ant-api).".into());
    }
    Ok(key)
}

/// Which user-supplied credential a named Claude account injects.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ClaudeCredential {
    SetupToken,
    ApiKey,
}
impl ClaudeCredential {
    /// Environment variable Claude Code reads this credential from.
    pub fn variable(self) -> &'static str {
        match self {
            Self::SetupToken => "CLAUDE_CODE_OAUTH_TOKEN",
            Self::ApiKey => "ANTHROPIC_API_KEY",
        }
    }
    fn name(self) -> &'static str {
        match self {
            Self::SetupToken => "setup-token",
            Self::ApiKey => "api-key",
        }
    }
    fn parse(name: &str) -> Option<Self> {
        match name {
            "setup-token" => Some(Self::SetupToken),
            "api-key" => Some(Self::ApiKey),
            _ => None,
        }
    }
    fn normalize(self, value: &str) -> Result<String, String> {
        match self {
            Self::SetupToken => normalize_claude_token(value),
            Self::ApiKey => normalize_claude_api_key(value),
        }
    }
}

/// Bind the ciphertext to its provider, account and kind, so a row copied to
/// another account or relabelled fails authentication.
fn associated_data(account: &str, kind: ClaudeCredential) -> Vec<u8> {
    format!(
        "monoptah-credential-v1\0{PROVIDER}\0{account}\0{}",
        kind.name()
    )
    .into_bytes()
}

/// The key operations report why they failed; this module words it for Claude.
fn read_failure(error: KeyError) -> String {
    match error {
        KeyError::Unreadable => UNAVAILABLE.into(),
        KeyError::SaveFailed => SAVE_FAILED.into(),
    }
}

/// Where each open store keeps its native-only tables, by data directory.
/// Profiles carry only their data directory, so this is how a profile finds
/// the database of the store it belongs to, wherever `--monocode-db` put it.
static DATABASES: std::sync::Mutex<Vec<(PathBuf, PathBuf)>> = std::sync::Mutex::new(Vec::new());

/// Record the database that holds credentials for `data_dir`. Called by the
/// store when it opens; the newest registration for a directory wins.
pub(crate) fn register_database(data_dir: &Path, database: &Path) {
    let mut databases = DATABASES.lock().unwrap_or_else(|e| e.into_inner());
    databases.retain(|(dir, _)| dir != data_dir);
    databases.push((data_dir.into(), database.into()));
}

/// The database registered for `data_dir`, if a store has opened there.
pub(crate) fn database_for(data_dir: &Path) -> Option<PathBuf> {
    DATABASES
        .lock()
        .unwrap_or_else(|e| e.into_inner())
        .iter()
        .find(|(dir, _)| dir == data_dir)
        .map(|(_, database)| database.clone())
}

impl Profile {
    fn database_path(&self) -> Result<PathBuf, String> {
        self.directory(Kind::Claude)?
            .ok_or("Add a named Claude account to configure a setup-token or API key.")?;
        let root = self.root.as_deref().unwrap_or(Path::new(""));
        DATABASES
            .lock()
            .unwrap_or_else(|e| e.into_inner())
            .iter()
            .find(|(dir, _)| dir == root)
            .map(|(_, database)| database.clone())
            .ok_or_else(|| "Claude credential storage is unavailable".to_owned())
    }
    fn key_path(database: &Path) -> Result<PathBuf, String> {
        Ok(database.parent().ok_or(UNAVAILABLE)?.join(KEY_FILE))
    }
    /// Open an existing database without creating it. `None` means there is
    /// no database yet, so there cannot be a saved credential.
    fn open_existing(&self) -> Result<Option<Connection>, String> {
        // Reading never fails just because no store has been opened for this
        // directory: nothing can have been saved there.
        let Ok(database) = self.database_path() else {
            return Ok(None);
        };
        if !database.exists() {
            return Ok(None);
        }
        let conn = Connection::open_with_flags(&database, OpenFlags::SQLITE_OPEN_READ_WRITE)
            .map_err(|_| UNAVAILABLE)?;
        conn.busy_timeout(std::time::Duration::from_secs(5))
            .map_err(|_| UNAVAILABLE)?;
        Ok(Some(conn))
    }
    fn stored(&self) -> Result<Option<StoredRow>, String> {
        let Some(conn) = self.open_existing()? else {
            return Ok(None);
        };
        match conn
            .query_row(
                "SELECT kind, nonce, ciphertext FROM provider_account_credentials
                 WHERE provider=?1 AND account_id=?2",
                params![PROVIDER, self.id],
                |row| Ok((row.get(0)?, row.get(1)?, row.get(2)?)),
            )
            .optional()
        {
            Ok(row) => Ok(row),
            // A database that predates the table has no credentials.
            Err(e) if e.to_string().contains("no such table") => Ok(None),
            Err(_) => Err(UNAVAILABLE.into()),
        }
    }
    /// Nonsecret local configuration, not a claim that the credential is valid.
    pub fn uses_claude_token(&self) -> Result<bool, String> {
        Ok(self.claude_credential()?.is_some())
    }
    /// The configured credential kind, read from the database row alone.
    pub fn claude_credential(&self) -> Result<Option<ClaudeCredential>, String> {
        if self.id == super::DEFAULT {
            return Ok(None);
        }
        let Some(conn) = self.open_existing()? else {
            return Ok(None);
        };
        let kind: Option<String> = match conn
            .query_row(
                "SELECT kind FROM provider_account_credentials WHERE provider=?1 AND account_id=?2",
                params![PROVIDER, self.id],
                |row| row.get(0),
            )
            .optional()
        {
            Ok(kind) => kind,
            Err(e) if e.to_string().contains("no such table") => None,
            Err(_) => return Err(UNAVAILABLE.into()),
        };
        kind.map(|name| ClaudeCredential::parse(&name).ok_or_else(|| UNAVAILABLE.to_owned()))
            .transpose()
    }
    pub fn save_claude_token(&self, value: &str) -> Result<(), String> {
        self.save_claude_credential(ClaudeCredential::SetupToken, value)
    }
    /// Saving one kind replaces the other in a single upsert: an account holds
    /// one secret, and a failed save leaves the previous row untouched.
    pub fn save_claude_credential(
        &self,
        kind: ClaudeCredential,
        value: &str,
    ) -> Result<(), String> {
        let secret = kind.normalize(value)?;
        let database = self.database_path()?;
        let key_path = Self::key_path(&database)?;
        // Never create the database here: a stray empty file would make the
        // store skip building its schema on the next launch.
        let mut conn = self.open_existing().ok().flatten().ok_or(SAVE_FAILED)?;
        conn.execute_batch(CREDENTIALS_TABLE)
            .map_err(|_| SAVE_FAILED)?;
        // A key is created only when the file is absent. A wrong-length file
        // is replaced only when no other account's row depends on it, and only
        // after the new row is written (see below).
        let mut replacement = None;
        let key = match inspect_key(&key_path).map_err(read_failure)? {
            KeyState::Valid(key) => key,
            KeyState::Missing => create_key(&key_path).map_err(read_failure)?,
            KeyState::WrongLength => {
                let others: i64 = conn
                    .query_row(
                        "SELECT count(*) FROM provider_account_credentials
                         WHERE NOT (provider=?1 AND account_id=?2)",
                        params![PROVIDER, self.id],
                        |row| row.get(0),
                    )
                    .map_err(|_| SAVE_FAILED)?;
                // Git credential tokens share this key file.
                let git: i64 =
                    match conn
                        .query_row("SELECT count(*) FROM git_credentials", [], |row| row.get(0))
                    {
                        Ok(count) => count,
                        Err(e) if e.to_string().contains("no such table") => 0,
                        Err(_) => return Err(SAVE_FAILED.into()),
                    };
                if others > 0 || git > 0 {
                    return Err(DAMAGED_KEY.into());
                }
                let key: [u8; KEY_LEN] = rand::random();
                replacement = Some((write_temp_key(&key_path, &key).map_err(read_failure)?, key));
                key
            }
        };
        let ciphertext = encrypt(&key, &associated_data(&self.id, kind), secret.as_bytes())
            .map_err(|_| SAVE_FAILED);
        let result = ciphertext.and_then(|(nonce, ciphertext)| {
            let tx = conn.transaction().map_err(|_| SAVE_FAILED)?;
            tx.execute(
                "INSERT INTO provider_account_credentials(provider, account_id, kind, nonce, ciphertext)
                 VALUES(?1, ?2, ?3, ?4, ?5)
                 ON CONFLICT(provider, account_id) DO UPDATE SET
                   kind=excluded.kind, nonce=excluded.nonce, ciphertext=excluded.ciphertext",
                params![PROVIDER, self.id, kind.name(), nonce.as_slice(), ciphertext],
            )
            .map_err(|_| SAVE_FAILED)?;
            // Swap the key in only once the row is written but not yet
            // committed: a failure on either side rolls the row back.
            if let Some((temporary, _)) = &replacement {
                std::fs::rename(temporary, &key_path).map_err(|_| SAVE_FAILED)?;
            }
            tx.commit().map_err(|_| SAVE_FAILED)?;
            Ok(())
        });
        if let Some((temporary, _)) = replacement {
            let _ = std::fs::remove_file(temporary);
        }
        // Only a committed change makes the last reading stale; a failed save
        // keeps the old credential, so its reading is still right.
        if result.is_ok() {
            self.forget_usage_reading();
        }
        result.map_err(Into::into)
    }
    /// Drop the setup-token usage reading, which belongs to the old credential.
    fn forget_usage_reading(&self) {
        if let Ok(Some(dir)) = self.directory(Kind::Claude) {
            crate::usage::claude_probe::forget(&dir);
        }
    }
    /// Remove only this saved credential, retaining the browser profile. It
    /// never reads or decrypts the row, so a lost key cannot block removal.
    pub fn remove_claude_token(&self) -> Result<(), String> {
        if self.id == super::DEFAULT {
            return Ok(());
        }
        let Some(conn) = self.open_existing().map_err(|_| CLEAR_FAILED)? else {
            return Ok(());
        };
        match conn.execute(
            "DELETE FROM provider_account_credentials WHERE provider=?1 AND account_id=?2",
            params![PROVIDER, self.id],
        ) {
            Ok(_) => {}
            Err(e) if e.to_string().contains("no such table") => {}
            Err(_) => return Err(CLEAR_FAILED.into()),
        }
        self.forget_usage_reading();
        Ok(())
    }
    /// The Claude credential saved for this account, `None` when there is none. Holds the
    /// secret: it is never logged. It goes to the CLI over stdin, or to api.anthropic.com in
    /// the Authorization header for the manual usage check.
    pub(crate) fn claude_secret(&self) -> Result<Option<(ClaudeCredential, String)>, String> {
        Ok(self
            .claude_secret_stamped()?
            .map(|(kind, secret, _)| (kind, secret)))
    }
    /// `claude_secret` with the row's nonce, read from one row so the two always
    /// belong together. The nonce is random on every save and not secret; the
    /// secret is handled as described there.
    fn claude_secret_stamped(&self) -> Result<Option<(ClaudeCredential, String, Vec<u8>)>, String> {
        let Some((name, nonce, ciphertext)) = self.stored()? else {
            return Ok(None);
        };
        let kind = ClaudeCredential::parse(&name).ok_or(UNAVAILABLE)?;
        if nonce.len() != NONCE_LEN {
            return Err(UNAVAILABLE.into());
        }
        let key = read_key(&Self::key_path(&self.database_path()?)?).map_err(read_failure)?;
        let plain = decrypt(&key, &associated_data(&self.id, kind), &nonce, &ciphertext)
            .map_err(|_| UNAVAILABLE)?;
        let secret = String::from_utf8(plain.to_vec()).map_err(|_| UNAVAILABLE)?;
        kind.normalize(&secret)
            .map(|secret| Some((kind, secret, nonce)))
            .map_err(|_| UNAVAILABLE.into())
    }
    /// The saved setup token with its row's nonce, for the manual usage check.
    /// Never an API key. The token is sent only to api.anthropic.com and never logged.
    pub(crate) fn claude_setup_token_stamped(&self) -> Result<Option<(String, Vec<u8>)>, String> {
        Ok(self
            .claude_secret_stamped()?
            .and_then(|(kind, secret, nonce)| {
                (kind == ClaudeCredential::SetupToken).then_some((secret, nonce))
            }))
    }
    /// Identifies the saved setup token without decrypting it: changes on
    /// every save, and is `None` for no credential or an API key.
    pub(crate) fn claude_setup_stamp(&self) -> Option<Vec<u8>> {
        let (name, nonce, _) = self.stored().ok()??;
        (ClaudeCredential::parse(&name)? == ClaudeCredential::SetupToken).then_some(nonce)
    }
    #[cfg(test)]
    fn claude_token(&self) -> Result<Option<String>, String> {
        Ok(self.claude_secret()?.map(|(_, secret)| secret))
    }
}

