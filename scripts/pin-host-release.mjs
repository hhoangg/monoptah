// Fork-local (Monoptah). Pins a published Monoptah Host release into the app:
//   node scripts/pin-host-release.mjs host-vX.Y.Z [--run <workflow run id>]
// It fetches host-release.json (preferably the artifact of the release workflow run,
// otherwise the release asset), verifies its build-provenance attestation, cross-checks
// every hash against the published .sha256 assets, and rewrites
// crates/monocode-core/src/remote/host_release.rs. Reading only the release would be
// trust-on-first-use; the attestation ties the hashes to the workflow that built them.
// It needs an authenticated `gh` and only reads from GitHub.
import { spawnSync } from "node:child_process";
import { mkdir, mkdtemp, readdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const REPO = "hhoangg/monoptah";
export const WORKFLOW = "host-release-monoptah.yml";
export const FLAVOR = "monoptah";
export const TARGETS = [
  "darwin-arm64",
  "darwin-x64",
  "linux-arm64",
  "linux-x64",
  "win32-arm64",
  "win32-x64",
];
const TAG_RE = /^host-v((?:0|[1-9]\d*)\.(?:0|[1-9]\d*)\.(?:0|[1-9]\d*))$/;
const HASH_RE = /^[0-9a-f]{64}$/;
const OUTPUT = join("crates", "monocode-core", "src", "remote", "host_release.rs");

export function parseTag(tag) {
  const match = typeof tag === "string" ? TAG_RE.exec(tag) : null;
  if (!match) throw new Error(`Invalid Host tag "${tag ?? ""}": use host-vX.Y.Z`);
  return match[1];
}

// Validates the parsed host-release.json against the tag and returns { version, assets }.
export function validateManifest(manifest, tag) {
  const plain = parseTag(tag);
  if (!manifest || typeof manifest !== "object")
    throw new Error("host-release.json is not an object");
  if (manifest.version !== `${plain}+${FLAVOR}`)
    throw new Error(
      `host-release.json version ${manifest.version} does not match ${plain}+${FLAVOR}`,
    );
  const assets = manifest.assets ?? {};
  const keys = Object.keys(assets).sort();
  if (keys.join(",") !== [...TARGETS].sort().join(","))
    throw new Error(`host-release.json targets are ${keys.join(", ")}, expected ${TARGETS.join(", ")}`);
  for (const target of TARGETS)
    if (!HASH_RE.test(assets[target]))
      throw new Error(`host-release.json has a bad sha256 for ${target}`);
  return { version: manifest.version, assets };
}

// Cross-checks the manifest hashes with the published .sha256 files
// ({ "monocode-host-<target>.tar.gz.sha256": "<content>" }).
export function crossCheck(assets, checksumFiles) {
  for (const target of TARGETS) {
    const names = Object.keys(checksumFiles).filter((name) =>
      new RegExp(`^monocode-host-${target}\\.(?:tar\\.gz|zip)\\.sha256$`).test(name),
    );
    if (names.length !== 1)
      throw new Error(`Expected one published .sha256 for ${target}, found ${names.length}`);
    const published = checksumFiles[names[0]].trim().split(/\s+/)[0];
    if (published !== assets[target])
      throw new Error(
        `Hash mismatch for ${target}: host-release.json has ${assets[target]}, the release has ${published}`,
      );
  }
}

// The X.Y.Z of the version pinned in a host_release.rs text, or null.
export function pinnedVersion(text) {
  const match = /HOST_VERSION: &str = "(\d+)\.(\d+)\.(\d+)\+/.exec(text);
  return match ? match.slice(1).map(Number) : null;
}

// -1, 0 or 1 comparing the X.Y.Z of `a` (an array) with the plain version string `b`.
export function compareCore(a, b) {
  const other = b.split("+")[0].split(".").map(Number);
  for (let i = 0; i < 3; i++) if (a[i] !== other[i]) return a[i] < other[i] ? -1 : 1;
  return 0;
}

export function renderHostRelease(tag, manifest) {
  const { version, assets } = validateManifest(manifest, tag);
  // Laid out as rustfmt would, so cargo fmt --check stays green.
  const rows = TARGETS.map(
    (target) => `    (\n        "${target}",\n        "${assets[target]}",\n    ),`,
  ).join("\n");
  return `//! The Monoptah Host release this app installs on remote machines.
//!
//! GENERATED by \`node scripts/pin-host-release.mjs ${tag}\`. Do not edit by hand: the
//! hashes come from the attested \`host-release.json\` of the release workflow run and
//! are cross-checked against the published \`.sha256\` assets.

/// Full Host version, as printed by \`monocode-host --version\`.
pub const HOST_VERSION: &str = "${version}";

/// Release download base. The tag has no \`+\`, which URLs would have to escape.
pub const HOST_RELEASE_BASE: &str =
    "https://github.com/${REPO}/releases/download/${tag}";

/// Expected sha256 of each package, by Host target.
pub const HOST_SHA256: [(&str, &str); ${TARGETS.length}] = [
${rows}
];

/// Pinned sha256 for a Host target such as \`linux-x64\`.
pub fn host_sha256(target: &str) -> Option<&'static str> {
    HOST_SHA256
        .iter()
        .find(|(name, _)| *name == target)
        .map(|(_, hash)| *hash)
}
`;
}

const defaultGh = (args, { cwd } = {}) => {
  const r = spawnSync("gh", args, { cwd, encoding: "utf8" });
  if (r.error) throw r.error;
  return { status: r.status, stdout: r.stdout ?? "", stderr: r.stderr ?? "" };
};
const ghOk = (gh, args, options) => {
  const r = gh(args, options);
  if (r.status !== 0) throw new Error(`gh ${args.join(" ")} failed: ${r.stderr.trim()}`);
  return r.stdout;
};

// Fetches host-release.json into `dir`; returns { file, source }.
async function fetchManifest(gh, tag, dir, runId) {
  let id = runId;
  if (!id) {
    const listed = gh([
      "run", "list", "-R", REPO, "--workflow", WORKFLOW, "--branch", tag,
      "--status", "success", "--limit", "1", "--json", "databaseId",
    ]);
    if (listed.status === 0) {
      try {
        id = String(JSON.parse(listed.stdout)[0]?.databaseId ?? "");
      } catch {
        id = "";
      }
    }
  }
  if (id) {
    const dest = join(dir, "run");
    await mkdir(dest, { recursive: true });
    const r = gh(["run", "download", id, "-R", REPO, "-n", "host-release-json", "-D", dest]);
    if (r.status === 0) return { file: join(dest, "host-release.json"), source: `run ${id}` };
  }
  const dest = join(dir, "release");
  await mkdir(dest, { recursive: true });
  ghOk(gh, ["release", "download", tag, "-R", REPO, "-p", "host-release.json", "-D", dest]);
  return { file: join(dest, "host-release.json"), source: `release ${tag}` };
}

// Pins `tag` into `root`. `gh` is injectable so tests never touch the network.
export async function pinHostRelease(tag, { root = process.cwd(), gh = defaultGh, runId } = {}) {
  const plain = parseTag(tag);
  // Never move the pin back: installed apps and Hosts only ever upgrade.
  let current = null;
  try {
    current = pinnedVersion(await readFile(join(root, OUTPUT), "utf8"));
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  const same = current !== null && compareCore(current, plain) === 0;
  if (current !== null && compareCore(current, plain) > 0)
    throw new Error(
      `Refusing to downgrade the pinned Host from ${current.join(".")} to ${plain}`,
    );
  const dir = await mkdtemp(join(tmpdir(), "pin-host-release-"));
  try {
    const { file, source } = await fetchManifest(gh, tag, dir, runId);
    // The attestation must come from this repository's Host release workflow, run on
    // this tag by a GitHub-hosted runner; any other signer is refused.
    ghOk(gh, [
      "attestation", "verify", file, "-R", REPO,
      "--signer-workflow", `${REPO}/.github/workflows/${WORKFLOW}`,
      "--source-ref", `refs/tags/${tag}`,
      "--deny-self-hosted-runners",
    ]);
    const manifest = JSON.parse(await readFile(file, "utf8"));
    const { assets } = validateManifest(manifest, tag);
    const sums = join(dir, "sums");
    await mkdir(sums);
    ghOk(gh, ["release", "download", tag, "-R", REPO, "-p", "monocode-host-*.sha256", "-D", sums]);
    const checksumFiles = {};
    for (const name of await readdir(sums))
      checksumFiles[name] = await readFile(join(sums, name), "utf8");
    crossCheck(assets, checksumFiles);
    // Write beside the target and rename, so a crash never leaves a half-written file.
    const target = join(root, OUTPUT);
    const temporary = `${target}.tmp-${process.pid}`;
    try {
      await writeFile(temporary, renderHostRelease(tag, manifest));
      await rename(temporary, target);
    } finally {
      await rm(temporary, { force: true });
    }
    return { source, version: manifest.version, output: OUTPUT, repinned: same };
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    const runAt = args.indexOf("--run");
    const runId = runAt >= 0 ? args.splice(runAt, 2)[1] : undefined;
    const result = await pinHostRelease(args[0], { runId });
    console.log(
      `${result.repinned ? "Re-pinned (same version)" : "Pinned"} ${result.version} from ${result.source} into ${result.output}`,
    );
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
